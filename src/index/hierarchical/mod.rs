//! Shared types and persisted formats for Zeppelin's hierarchical IVF index.
//!
//! Hierarchical IVF is an approximate-nearest-neighbor (ANN) index that replaces
//! one large, flat centroid table with a tree of smaller centroid tables. A
//! query follows the closest centroids one level at a time, then scans selected
//! leaf clusters exactly or with quantized coarse ranking. Keeping several paths
//! at each level (the *beam*) improves recall at the cost of more object reads
//! and distance calculations.
//!
//! This module is the boundary shared by [`build`] and [`search`]. It defines
//! the JSON metadata object, the binary tree-node format, object-store key
//! conventions, and [`HierarchicalIndex`], the in-memory handle implementing
//! [`crate::index::VectorIndex`]. Leaf vector, attribute, bitmap, SQ8, and PQ
//! artifacts deliberately reuse the IVF-Flat formats.
//!
//! ```text
//! manifest-visible hierarchical segment
//!                 |
//!                 v
//!        tree_meta.json (root id, shape, encoding)
//!                 |
//!                 v
//!          node_<root>.bin
//!          /             \
//!   node_<child>.bin    numeric leaf-cluster id
//!          |                     |
//!          +----------+----------+
//!                     v
//!       cluster_N.bin + attrs_N.bin
//!       (+ bitmap/SQ8/PQ sidecars when configured)
//! ```
//!
//! Objects under a segment prefix are immutable build outputs. Their existence
//! in S3 or MinIO does **not** make the segment visible: the namespace manifest
//! remains authoritative, and the compaction layer publishes the completed
//! segment separately. Memory and local disk may cache these immutable bytes,
//! but neither cache can establish visibility.
//!
//! ## Reading map
//!
//! 1. Start with [`TreeMeta`] to understand the persisted tree description.
//! 2. Read [`TreeNode`] and [`serialize_tree_node`] for the per-node artifact.
//! 3. Read [`build::build_hierarchical`] for bottom-up construction.
//! 4. Read [`search::search_hierarchical`] for mixed-depth beam traversal and
//!    leaf reranking.
//! 5. Use [`HierarchicalIndex::load`] for the metadata-only query entry point.
//!
//! ## Invariants
//!
//! - Every centroid and its child identifier occupy the same position.
//! - Numeric child identifiers name leaf clusters; generated non-numeric IDs
//!   name tree-node objects. Mixed-depth nodes can contain both kinds.
//! - All centroids and vectors in one segment use [`TreeMeta::dim`].
//! - Persisted tree and leaf artifacts are write-once. Only a manifest update
//!   can make the completed segment visible to queries.
//! - Increasing the beam width explores more branches and normally improves
//!   recall, but also increases reads, bytes, CPU, and potentially latency.
//!
//! ## Rust concepts used here
//!
//! [`TreeMeta`] uses serde derives because it is a versioned JSON artifact;
//! `#[serde(default)]` keeps older metadata readable when embedded SQ8
//! calibration is absent. Java might use a JSON DTO with a nullable field, and
//! C would require an explicit decoder and presence flag. Rust's
//! [`Option`] makes the two format states explicit.
//!
//! The async trait implementation is generated by `async_trait`. It lets the
//! common index interface expose asynchronous object-store work even though
//! stable Rust traits do not directly provide object-safe `async fn` methods in
//! the way a Java interface returns `CompletableFuture`. Borrowed slices and
//! strings keep large vector batches and key components under caller ownership;
//! unlike C pointers, those borrows are non-null and lifetime checked.

