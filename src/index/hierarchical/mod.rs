/// Persisted description needed to open a hierarchical segment.
///
/// The builder writes this value as `tree_meta.json` after constructing tree
/// nodes and leaf artifacts. Loading it proves that the metadata object exists;
/// it does not prove manifest visibility. The namespace manifest is the
/// authoritative list of queryable segments.
///
/// Cloning this value duplicates owned strings and calibration bytes. Serde's
/// JSON representation is a compatibility boundary, so field meaning and
/// defaults must remain stable for already-written segments.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TreeMeta {
    /// Greatest depth recorded during construction; one denotes a root that
    /// points directly to leaf clusters.
    pub num_levels: usize,
    /// Requested maximum centroids per internal node.
    ///
    /// Empty k-means partitions are omitted, so an individual node may have
    /// fewer children than this target.
    pub branching_factor: usize,
    /// Number of source vectors represented by all leaf clusters.
    pub total_vectors: usize,
    /// Required component count for every stored vector, centroid, and query.
    pub dim: usize,
    /// Non-numeric identifier used to construct the root node's object key.
    pub root_node_id: String,
    /// Count of globally numbered leaf clusters, with valid IDs in
    /// `0..num_leaf_clusters`.
    pub num_leaf_clusters: usize,
    /// Coarse encoding used before full-precision reranking at leaf level.
    pub quantization: QuantizationType,
    /// Serialized SQ8 calibration embedded by current scalar-quantized builds.
    ///
    /// Older tree metadata omits this field and scalar search falls back to
    /// `sq_calibration.bin`.
    #[serde(default)]
    pub sq_calibration: Option<Vec<u8>>,
}

/// One immutable centroid-routing node stored as a binary object.
///
/// Each centroid routes to the child identifier at the same vector position.
/// Numeric identifiers refer to IVF-compatible leaf clusters; non-numeric IDs
/// refer to other [`TreeNode`] objects. An uneven k-means split can create a
/// mixed-depth node containing both kinds. In that state `is_leaf` is `false`,
/// and search recognizes the numeric children individually.
#[derive(Debug, Clone)]
pub struct TreeNode {
    /// Routing centroids in the segment's fixed vector dimension.
    pub centroids: Vec<Vec<f32>>,
    /// Positionally aligned node IDs or decimal leaf-cluster indexes.
    pub children: Vec<String>,
    /// Whether every child is a leaf cluster rather than another tree node.
    pub is_leaf: bool,
}

/// Lightweight in-memory handle to one immutable hierarchical segment.
///
/// Only [`TreeMeta`] and key-building context are held eagerly. Search fetches
/// tree nodes and selected leaf artifacts lazily through the optional tiered
/// cache. `bitmap_fields` comes from the manifest-facing query layer; a direct
/// metadata load leaves it empty and therefore uses exact attribute filtering.
///
/// Cloning the handle clones its owned metadata and strings; it does not clone
/// remote segment data or share mutable index state.
#[derive(Debug, Clone)]
pub struct HierarchicalIndex {
    /// Persisted tree shape, vector count, dimension, and leaf encoding.
    pub(crate) meta: TreeMeta,
    /// Namespace prefix used only to derive immutable object-store keys.
    pub(crate) namespace: String,
    /// Physical namespace owning the immutable tree and leaf artifacts.
    pub(crate) physical_namespace: String,
    /// Incarnation-qualified owner used to prevent disposable-cache aliasing.
    pub(crate) physical_origin: Option<ArtifactOrigin>,
    /// Manifest segment identifier used only to derive object-store keys.
    pub(crate) segment_id: String,
    /// Manifest-declared fields whose leaf clusters may have bitmap sidecars.
    pub(crate) bitmap_fields: Vec<String>,
    /// Exact routing-node identifiers written by this build.
    ///
    /// Metadata-only loads of legacy segments leave this empty. Manifest
    /// publication records the populated build-time inventory so receipts and
    /// clones root every lazily fetched internal node.
    pub(crate) routing_node_ids: Vec<String>,
}

