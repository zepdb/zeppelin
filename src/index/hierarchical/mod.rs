/// Constructs the object-store key for a segment's hierarchical metadata.
///
/// # Parameters
///
/// - `namespace`: Already-validated namespace key prefix.
/// - `segment_id`: Immutable segment identifier under that namespace.
///
/// # Returns
///
/// An owned key ending in `tree_meta.json`.
///
/// # Examples
///
/// Namespace `images` and segment `01ABC` produce
/// `images/segments/01ABC/tree_meta.json`.
pub fn tree_meta_key(namespace: &str, segment_id: &str) -> String {
    format!("{namespace}/segments/{segment_id}/tree_meta.json")
}

/// Constructs the object-store key for one binary routing node.
///
/// # Parameters
///
/// - `namespace`: Already-validated namespace key prefix.
/// - `segment_id`: Immutable segment identifier.
/// - `node_id`: Generated non-numeric routing-node identifier.
///
/// # Returns
///
/// An owned key ending in `node_<node_id>.bin`.
///
/// # Examples
///
/// Node `root` in segment `seg_1` becomes
/// `ns/segments/seg_1/node_root.bin`.
pub fn tree_node_key(namespace: &str, segment_id: &str, node_id: &str) -> String {
    format!("{namespace}/segments/{segment_id}/node_{node_id}.bin")
}

